#!/usr/bin/env node
// Turns the CSV from supabase/phase4_schema_export.sql into one SQL file that
// rebuilds the database: node tests/db/build_baseline.js export.csv > supabase/migrations/0000_baseline.sql
"use strict";
const fs = require("fs");

function parseCsv(text) {
  const rows = []; let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { row.push(cell); cell = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += ch;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.length > 1 || r[0] !== "");
}

function build(csvText, source) {
  const rows = parseCsv(csvText);
  const head = rows.shift().map(h => h.trim().toLowerCase());
  const at = k => head.indexOf(k);
  if (at("ord") < 0 || at("name") < 0 || at("ddl") < 0) throw new Error("Expected the columns ord, name, ddl (from supabase/phase4_schema_export.sql)");
  const items = rows.map(r => ({ ord: Number(r[at("ord")]), name: r[at("name")], ddl: r[at("ddl")] }))
    .filter(x => x.ddl && x.ddl.trim())
    .sort((a, b) => a.ord - b.ord || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const out = [
    "-- SEA ESTATES baseline: rebuilds the database schema from scratch.",
    "-- Generated by tests/db/build_baseline.js from " + (source || "a schema export") + ".",
    "-- Do not edit by hand: change the database with a new numbered migration.",
    "set check_function_bodies = off;",
    "set client_min_messages = warning;",
    ""
  ];
  let last = null;
  for (const it of items) {
    if (it.ord !== last) { out.push("-- " + ({ 1: "extensions", 2: "enums", 3: "functions", 4: "sequences", 5: "tables", 6: "keys and checks", 7: "foreign keys", 8: "indexes", 9: "views", 10: "functions that return table rows", 11: "row-level security", 12: "triggers", 13: "policies", 14: "table rights", 15: "column rights", 16: "function rights", 17: "default rights", 18: "storage buckets" }[it.ord] || "other")); last = it.ord; }
    // One line ending everywhere: git (and git am) would otherwise strip the
    // carriage returns some function bodies carry, and the file would drift.
    let ddl = it.ddl.replace(/\r\n?/g, "\n").trim();
    // Extensions may not exist on every Postgres (CI): don't stop the build for one.
    if (it.ord === 1) ddl = "do $$ begin " + ddl.replace(/'/g, "''").replace(/^(.*)$/, "execute '$1'") + "; exception when others then raise notice 'extension skipped: %', sqlerrm; end $$";
    out.push(ddl.replace(/;\s*$/, "") + ";");
    out.push("");
  }
  return out.join("\n");
}

if (require.main === module) {
  const file = process.argv[2];
  if (!file) { console.error("usage: node tests/db/build_baseline.js export.csv > supabase/migrations/0000_baseline.sql"); process.exit(2); }
  process.stdout.write(build(fs.readFileSync(file, "utf8"), require("path").basename(file)));
}
module.exports = { parseCsv, build };
