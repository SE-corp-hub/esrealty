-- SEA ESTATES · Phase 4 schema export (read-only, changes nothing)
--
-- Run in the Supabase SQL editor AFTER every step of the current update is
-- done. If it shows "Potential issue detected ... Row Level Security", choose
-- "Run without RLS" (this query creates nothing). Then use the result's
-- "Export" / "Download CSV" button and attach the file to the chat. Claude
-- turns it into supabase/migrations/0000_baseline.sql: one file that rebuilds
-- this database from scratch, so the access rules can be tested on GitHub for
-- every change.
--
-- One row per statement, in the order they must run:
--   ord 1 extensions · 2 enums · 3 functions · 4 sequences · 5 tables
--   6 constraints (keys and checks) · 7 foreign keys · 8 indexes · 9 views
--   10 functions that return table rows · 11 row-level security switches
--   12 triggers · 13 policies · 14 table rights · 15 column rights
--   16 function rights · 17 default rights · 18 storage buckets
-- Covers the public schema, plus the storage policies and buckets and the
-- triggers on auth.users that call public functions. No row data is exported.

with
  pub as (select oid from pg_namespace where nspname = 'public'),
  ext as (
    select 1 as ord, e.extname::text as name,
           format('create extension if not exists %I with schema %I', e.extname, n.nspname) as ddl
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname <> 'plpgsql'
  ),
  enums as (
    select 2, t.typname::text,
           format('create type public.%I as enum (%s)', t.typname,
                  (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
    from pg_type t where t.typnamespace = (select oid from pub) and t.typtype = 'e'
  ),
  -- Functions whose result or arguments are a table's row type can only be
  -- created after that table (and view); the rest come before the tables,
  -- because column defaults call them.
  rowtyped as (
    select p.oid from pg_proc p
    where p.pronamespace = (select oid from pub)
      and exists (select 1 from pg_type t join pg_class c on c.oid = t.typrelid
                  where c.relkind in ('r', 'p', 'v') and (t.oid = p.prorettype or t.oid = any (p.proargtypes)))
  ),
  funcs as (
    select case when p.oid in (select oid from rowtyped) then 10 else 3 end, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
           pg_get_functiondef(p.oid)
    from pg_proc p
    where p.pronamespace = (select oid from pub) and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  ),
  seqs as (
    select 4, c.relname::text,
           format('create sequence if not exists public.%I', c.relname)
    from pg_class c
    where c.relnamespace = (select oid from pub) and c.relkind = 'S'
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')  -- identity sequences come with their column
  ),
  tabs as (
    select 5, c.relname::text,
           format('create table if not exists public.%I (%s)', c.relname,
             (select string_agg(
                format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
                || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
                || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                        when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
                || case when a.attnotnull then ' not null' else '' end,
                ', ' order by a.attnum)
              from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
              where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped))
    from pg_class c where c.relnamespace = (select oid from pub) and c.relkind in ('r', 'p')
  ),
  cons as (
    select case when k.contype = 'f' then 7 else 6 end, c.relname || '.' || k.conname,
           format('alter table public.%I add constraint %I %s', c.relname, k.conname, pg_get_constraintdef(k.oid))
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where c.relnamespace = (select oid from pub) and k.contype in ('p', 'u', 'c', 'f', 'x')
  ),
  idx as (
    select 8, i.relname::text, pg_get_indexdef(i.oid)
    from pg_index x join pg_class i on i.oid = x.indexrelid join pg_class t on t.oid = x.indrelid
    where t.relnamespace = (select oid from pub)
      and not exists (select 1 from pg_constraint k where k.conindid = i.oid)
  ),
  views as (
    select 9, c.relname::text,
           format('create or replace view public.%I%s as %s', c.relname,
                  case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
                  pg_get_viewdef(c.oid, true))
    from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'v'
  ),
  rls as (
    select 11, c.relname::text,
           format('alter table public.%I enable row level security', c.relname)
           || case when c.relforcerowsecurity then format('; alter table public.%I force row level security', c.relname) else '' end
    from pg_class c where c.relnamespace = (select oid from pub) and c.relkind in ('r', 'p') and c.relrowsecurity
  ),
  trg as (
    select 12, n.nspname || '.' || c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid)
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
    join pg_proc f on f.oid = t.tgfoid
    where not t.tgisinternal
      and (n.nspname = 'public' or (n.nspname = 'auth' and f.pronamespace = (select oid from pub)))
  ),
  pols as (
    select 13, p.schemaname || '.' || p.tablename || '.' || p.policyname,
           format('create policy %I on %I.%I as %s for %s to %s%s%s',
                  p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
                  array_to_string(array(select quote_ident(r) from unnest(p.roles) r), ', '),
                  case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
                  case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
    from pg_policies p
    where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
  ),
  tgrants as (
    select 14, c.relname || ' :: ' || a.grantee::regrole::text,
           format('grant %s on public.%I to %s', string_agg(a.privilege_type, ', ' order by a.privilege_type), c.relname, quote_ident(a.grantee::regrole::text))
    from pg_class c, aclexplode(c.relacl) a
    where c.relnamespace = (select oid from pub) and c.relkind in ('r', 'p', 'v', 'S')
      and a.grantee <> 0 and a.grantee::regrole::text in ('anon', 'authenticated', 'service_role')
    group by c.relname, a.grantee
  ),
  cgrants as (
    select 15, c.relname || '.' || att.attname || ' :: ' || a.grantee::regrole::text,
           -- each right takes its own column list: "grant insert (x), update (x)"
           format('grant %s on public.%I to %s', string_agg(a.privilege_type || ' (' || quote_ident(att.attname) || ')', ', ' order by a.privilege_type), c.relname, quote_ident(a.grantee::regrole::text))
    from pg_class c join pg_attribute att on att.attrelid = c.oid, aclexplode(att.attacl) a
    where c.relnamespace = (select oid from pub) and att.attacl is not null and a.grantee <> 0
      and a.grantee::regrole::text in ('anon', 'authenticated', 'service_role')
    group by c.relname, att.attname, a.grantee
  ),
  fgrants as (
    select 16, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
           format('revoke all on function public.%I(%s) from public, anon, authenticated', p.proname, pg_get_function_identity_arguments(p.oid))
           || coalesce((select '; ' || string_agg(format('grant execute on function public.%I(%s) to %s', p.proname, pg_get_function_identity_arguments(p.oid), quote_ident(a.grantee::regrole::text)), '; ')
                        from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                        where a.privilege_type = 'EXECUTE' and a.grantee <> 0 and a.grantee::regrole::text in ('anon', 'authenticated', 'service_role')), '')
           || case when exists (select 1 from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a where a.grantee = 0)
                   then format('; grant execute on function public.%I(%s) to public', p.proname, pg_get_function_identity_arguments(p.oid)) else '' end
    from pg_proc p
    where p.pronamespace = (select oid from pub) and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  ),
  dgrants as (
    select 17, d.defaclrole::regrole::text || ' ' || d.defaclobjtype::text || ' ' || a.grantee::regrole::text,
           format('alter default privileges for role %s in schema public grant %s on %s to %s',
                  quote_ident(d.defaclrole::regrole::text),
                  string_agg(a.privilege_type, ', ' order by a.privilege_type),
                  case d.defaclobjtype when 'r' then 'tables' when 'S' then 'sequences' when 'f' then 'functions' else 'types' end,
                  quote_ident(a.grantee::regrole::text))
    from pg_default_acl d, aclexplode(d.defaclacl) a
    where d.defaclnamespace = (select oid from pub) and a.grantee <> 0
      and a.grantee::regrole::text in ('anon', 'authenticated', 'service_role')
    group by d.defaclrole, d.defaclobjtype, a.grantee
  ),
  buckets as (
    select 18, b.id::text,
           format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing',
                  b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'),
                  coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
    from storage.buckets b
  )
select ord, name, ddl from (
  select * from ext union all select * from enums union all select * from funcs
  union all select * from seqs union all select * from tabs union all select * from cons
  union all select * from idx union all select * from views union all select * from rls
  union all select * from trg union all select * from pols union all select * from tgrants
  union all select * from cgrants union all select * from fgrants union all select * from dgrants
  union all select * from buckets
) x (ord, name, ddl)
order by ord, name;
